#' @title Read API-Pop Output
#'
#' @description
#' Reads the weekly aggregated rumor data produced by API-Pop.
#' Automatically detects if the file uses commas (,) or semicolons (;) as separators.
#'
#' @param path Character string. The file path to the CSV file.
#'
#' @return A tibble (data frame) containing the raw data.
#'
#' @importFrom readr read_csv read_csv2
#' @export
read_api_pop_output <- function(path) {
  # Read the first line to guess the separator, suppressing incomplete line warnings
  first_line <- readLines(path, n = 1, warn = FALSE)
  
  # Check if the header contains a semicolon
  if (grepl(";", first_line)) {
    # Use read_csv2 for semicolon-separated files (common in LATAM/Europe)
    return(readr::read_csv2(path, show_col_types = FALSE))
  } else {
    # Use read_csv for standard comma-separated files
    return(readr::read_csv(path, show_col_types = FALSE))
  }
}


#' @title Standardise and Validate Input Columns
#'
#' @description
#' Cleans the column names of the uploaded CSV, checks for required fields,
#' resolves aliases for case and population columns, and zero-pads the 
#' geographic codes (e.g., department and fraction IDs) based on the strict 
#' string lengths defined in the configuration file.
#'
#' @param df Data frame. The raw combined data read from the CSV files.
#' @param config List. The parsed configuration object loaded from config.json.
#' @param active_country Character string. The target country block to read from the config.
#'
#' @return A validated and standardized tibble ready for spatial aggregation.
#'
#' @importFrom dplyr mutate
#' @importFrom stringr str_pad
#' @importFrom purrr keep
#' @export
standardise_input_columns <- function(df, config, active_country) {
  
  # 1. Lowercase conversion
  names(df) <- tolower(names(df))
  
  # 2. Alias resolution (Fuzzy matching for numeric targets)
  candidates <- list(
    n_cases    = c("n_cases", "cases", "count", "n"),
    population = c("population", "n_population", "pop", "denominator")
  )
  
  for (std in names(candidates)) {
    hits <- candidates[[std]][candidates[[std]] %in% names(df)]
    if (length(hits) == 0) stop(sprintf("Required column for '%s' not found.", std))
    # Rename if the found alias isn't already the standard name
    if (hits[1] != std) names(df)[names(df) == hits[1]] <- std
  }
  
  # 3. Strict validation for core variables
  required <- c("country", "level2", "level3", "year", "week", "n_cases", "population")
  missing  <- setdiff(required, names(df))
  
  if (length(missing) > 0) {
    stop(sprintf("Missing required columns: %s", paste(missing, collapse = ", ")))
  }
  
  # 4. Retrieve Dynamic Zero-Padding Rules from Config
  mappings <- config[[active_country]]$mapping
  
  # Search the config mapping block to find the exact code lengths assigned to level2 and level3
  lvl2_len <- purrr::keep(mappings, ~ .x$csv_column == "level2")[[1]]$code_length
  lvl3_len <- purrr::keep(mappings, ~ .x$csv_column == "level3")[[1]]$code_length
  
  # 5. Type Casting and Zero-Padding
  df %>%
    dplyr::mutate(
      level2 = stringr::str_pad(as.character(level2), width = lvl2_len, pad = "0"),
      level3 = stringr::str_pad(as.character(level3), width = lvl3_len, pad = "0")
    )
}


#' @title Combine and Standardise Uploaded CSV Files
#'
#' @description
#' Acts as the master ingestion controller. It reads multiple API-Pop CSV files 
#' simultaneously, binds them into a single data frame while tracking their 
#' origin via a file index, and applies column standardisation and zero-padding 
#' rules based on the active country's configuration.
#'
#' @param file_paths Character vector. The temporary file paths generated by 
#'        the Shiny file upload widget (e.g., \code{input$file_upload$datapath}).
#' @param config List. The parsed configuration object loaded from config.json.
#' @param active_country Character string. The target country block to read from 
#'        the configuration (e.g., "Argentina").
#'
#' @return A validated, standardized, and zero-padded tibble (data frame) 
#'         ready for spatial aggregation.
#'
#' @importFrom purrr map_dfr
#' @export
combine_uploaded_data <- function(file_paths, config, active_country) {
  # 1. Read and bind all files, tracking their origin for deduplication
  raw_df <- purrr::map_dfr(file_paths, read_api_pop_output, .id = "file_index")
  
  # 2. Standardise columns and apply zero-padding rules from the config
  standardise_input_columns(raw_df, config, active_country)
}


#' @title Prepare Geospatial Dataset
#'
#' @description
#' Filters the standardized API-Pop data to a specific time window, dynamically 
#' truncates geographic codes to roll up to the requested administrative level 
#' (based on configuration lengths), aggregates cases and population, and 
#' calculates the consultation-based prevalence per 100,000 inhabitants.
#'
#' @param df Data frame. The standardized data from \code{combine_uploaded_data}.
#' @param selected_level Character string. The geographic level selected in the UI.
#' @param selected_year Integer. The chosen epidemiological year.
#' @param week_from Integer. The start week of the analysis window.
#' @param week_to Integer. The end week of the analysis window.
#' @param config List. The parsed configuration object loaded from config.json.
#' @param active_country Character string. The target country block to read from the config.
#'
#' @return A summarized tibble with analysis_unit_id, n_cases, population, n_weeks, and prevalence_100k.
#'
#' @importFrom dplyr filter mutate group_by summarise n
#' @export
prepare_geospatial_dataset <- function(df,
                                       selected_level,
                                       selected_year,
                                       week_from,
                                       week_to,
                                       config,
                                       active_country) {
  
  # 1. Time Filtering
  df_filtered <- df %>%
    dplyr::filter(year == selected_year, week >= week_from, week <= week_to)
  
  if (nrow(df_filtered) == 0) return(NULL)
  
  # 2. Retrieve geographic mapping rules from config
  mappings   <- config[[active_country]]$mapping
  target_len <- mappings[[selected_level]]$code_length
  
  # 3. Hierarchical Truncation (The Roll-up)
  # We always use level3 (the finest resolution code) and truncate it upwards
  # substr() chops the string starting at character 1, stopping at target_len
  df_filtered <- df_filtered %>%
    dplyr::mutate(
      analysis_unit_id = substr(level3, 1, target_len)
    )
  
  # Helper function to grab the first non-NA population to avoid double-counting
  first_pop <- function(x) {
    valid <- na.omit(x)
    if (length(valid) > 0) valid[1] else NA_real_
  }
  
  # 4. Aggregation & Prevalence Calculation
  df_agg <- df_filtered %>%
    dplyr::group_by(analysis_unit_id) %>%
    dplyr::summarise(
      n_cases    = sum(n_cases, na.rm = TRUE),
      population = first_pop(population),
      n_weeks    = dplyr::n_distinct(week), 
      .groups    = "drop"
    ) %>%
    dplyr::mutate(
      prevalence_100k = (n_cases / population) * 100000
    ) %>%
    # Filter out rows where population was missing/zero to avoid Infinite (Inf) values
    dplyr::filter(population > 0, !is.na(population))
  
  return(df_agg)
}
